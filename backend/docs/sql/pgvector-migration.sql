-- =====================================================================
-- Chuyển cột embedding sang kiểu vector(768) của pgvector và tạo index HNSW (khoảng cách cosine).
-- DB cũ có document_chunks.embedding kiểu real[]. ddl-auto=update (Hibernate 7) có thử tự đổi kiểu nhưng bỏ qua
-- nếu lỗi (chưa có extension, vector sai số chiều); khi đó app dừng lúc khởi động (PgVectorSchemaCheck) cho tới
-- khi chạy script này. Script là cách chính thức, rõ ràng: kiểm tra số chiều trước rồi mới cast.
--
-- Cần cài pgvector trên máy chủ PostgreSQL trước (xem docs/pgvector-setup.md). Chạy được TRƯỚC hoặc SAU lần
-- khởi động đầu với code mới; chạy lại nhiều lần vẫn an toàn (idempotent). Dữ liệu cũ được cast giữ nguyên,
-- không phải embed lại. Toàn bộ nằm trong một transaction: lỗi ở đâu thì không đổi gì.
--   psql -U postgres -h localhost -d brainblocks -v ON_ERROR_STOP=1 -f docs/sql/pgvector-migration.sql
-- =====================================================================
BEGIN;

-- Cần quyền tạo extension (thường là user postgres); đã có thì bỏ qua.
CREATE EXTENSION IF NOT EXISTS vector;

DO $$
BEGIN
    IF to_regclass('document_chunks') IS NOT NULL
       AND (SELECT format_type(a.atttypid, a.atttypmod) FROM pg_attribute a
            WHERE a.attrelid = to_regclass('document_chunks') AND a.attname = 'embedding' AND NOT a.attisdropped)
           <> 'vector(768)' THEN
        -- vector(768) bắt buộc đúng 768 chiều: có dòng sai chiều thì dừng, không cast nửa chừng.
        IF EXISTS (SELECT 1 FROM document_chunks
                   WHERE embedding IS NOT NULL AND cardinality(embedding) <> 768) THEN
            RAISE EXCEPTION 'document_chunks has embeddings whose dimension is not 768; reindex those documents first';
        END IF;
        ALTER TABLE document_chunks ALTER COLUMN embedding TYPE vector(768) USING embedding::vector(768);
        RAISE NOTICE 'document_chunks.embedding converted to vector(768)';
    END IF;
END $$;

-- Vector ngữ nghĩa của sản phẩm cho chatbot (entity ProductEmbedding). Hibernate cũng tự tạo bảng này; tạo sẵn ở
-- đây (cùng định nghĩa) để tạo được index ngay. Xóa sản phẩm thì xóa theo vector (ON DELETE CASCADE).
DO $$
BEGIN
    IF to_regclass('products') IS NOT NULL THEN
        CREATE TABLE IF NOT EXISTS product_embeddings (
            id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            product_id   bigint       NOT NULL,
            embedding    vector(768)  NOT NULL,
            content_hash varchar(64)  NOT NULL,
            updated_at   timestamp(6) NOT NULL,
            CONSTRAINT uk_product_embeddings_product UNIQUE (product_id),
            CONSTRAINT fk_product_embeddings_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE
        );
    END IF;
END $$;

DO $$
BEGIN
    IF to_regclass('document_chunks') IS NOT NULL THEN
        CREATE INDEX IF NOT EXISTS idx_document_chunks_embedding_hnsw
            ON document_chunks USING hnsw (embedding vector_cosine_ops);
    END IF;
    IF to_regclass('product_embeddings') IS NOT NULL THEN
        CREATE INDEX IF NOT EXISTS idx_product_embeddings_embedding_hnsw
            ON product_embeddings USING hnsw (embedding vector_cosine_ops);
    END IF;
END $$;

COMMIT;
